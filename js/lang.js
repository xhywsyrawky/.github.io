// 默认语言
let currentLang = 'zh';

// 语言切换执行引擎
window.changeLanguage = function(langCode) {
    if (!window.translations[langCode]) return;
    currentLang = langCode;
    
    // 保存到localStorage中方便跨页面保持
    localStorage.setItem('voicforyou_lang', langCode);
    
    // 更新页面上带有 data-i18n 的元素
    document.querySelectorAll('[data-i18n]').forEach(elem => {
        const key = elem.getAttribute('data-i18n');
        if (window.translations[langCode][key] !== undefined) {
            // 如果是 data-i18n-html，可以用 innerHTML，否则用 textContent 确保安全
            if (elem.hasAttribute('data-i18n-html')) {
                elem.innerHTML = window.translations[langCode][key];
            } else {
                elem.textContent = window.translations[langCode][key];
            }
        }
    });

    // 更新页面上带有 data-i18n-placeholder 的输入框
    document.querySelectorAll('[data-i18n-placeholder]').forEach(elem => {
        const key = elem.getAttribute('data-i18n-placeholder');
        if (window.translations[langCode][key] !== undefined) {
            elem.setAttribute('placeholder', window.translations[langCode][key]);
        }
    });
    
    // 触发一个自定义事件，方便页面内的其他脚本（如donation.js）在语言变化时重新计算
    const event = new CustomEvent('languageChanged', { detail: { lang: langCode } });
    document.dispatchEvent(event);

    // 高亮当前选中的语言按钮
    document.querySelectorAll('.lang-btn').forEach(btn => {
        if (btn.getAttribute('data-lang') === langCode) {
            btn.classList.add('active');
        } else {
            btn.classList.remove('active');
        }
    });
    
    // 设置文档语言属性，利于SEO和屏幕阅读器识别
    document.documentElement.lang = langCode;
};

// 初始化语言
document.addEventListener('DOMContentLoaded', () => {
    // 优先读取本地缓存，无则采用中文
    const savedLang = localStorage.getItem('voicforyou_lang') || 'zh';
    
    // 给所有多语言切换按钮绑定事件
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.getAttribute('data-lang');
            window.changeLanguage(lang);
        });
    });
    
    window.changeLanguage(savedLang);
});
